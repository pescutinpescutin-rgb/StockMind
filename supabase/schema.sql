create table if not exists public.watchlist (
    user_id uuid not null references auth.users(id) on delete cascade,
    symbol text not null,
    added_at timestamptz not null default now(),
    primary key (user_id, symbol)
);

alter table public.watchlist enable row level security;
drop policy if exists "Users manage their watchlist" on public.watchlist;
create policy "Users manage their watchlist"
    on public.watchlist for all
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

create table if not exists public.portfolio (
    user_id uuid not null references auth.users(id) on delete cascade,
    symbol text not null,
    shares double precision not null check (shares > 0),
    avg_cost double precision not null check (avg_cost >= 0),
    updated_at timestamptz not null default now(),
    primary key (user_id, symbol)
);

alter table public.portfolio enable row level security;
drop policy if exists "Users manage their portfolio" on public.portfolio;
create policy "Users manage their portfolio"
    on public.portfolio for all
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

create table if not exists public.alerts (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    symbol text not null,
    direction text not null check (direction in ('above', 'below')),
    target double precision not null check (target > 0),
    legacy_id integer,
    created_at timestamptz not null default now(),
    unique (user_id, legacy_id)
);

alter table public.alerts enable row level security;
drop policy if exists "Users manage their alerts" on public.alerts;
create policy "Users manage their alerts"
    on public.alerts for all
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

create table if not exists public.legacy_imports (
    user_id uuid primary key references auth.users(id) on delete cascade,
    imported_at timestamptz not null default now()
);

grant select, insert, update, delete
    on public.watchlist, public.portfolio, public.alerts, public.legacy_imports
    to authenticated;
grant usage, select on sequence public.alerts_id_seq to authenticated;

alter table public.legacy_imports enable row level security;
drop policy if exists "Users manage their import status" on public.legacy_imports;
create policy "Users manage their import status"
    on public.legacy_imports for all
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);
